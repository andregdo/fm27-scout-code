//! The signature that opens the name pool: six little-endian `u32` words,
//! `[46421, 0, 1024, 256, 2048, 0]`.

pub const NAME_POOL_SIGNATURE: [u8; 24] = [
    0x55, 0xB5, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
    0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
];

/// The first signature word plus one zero byte, used to locate candidate pools.
pub const NAME_POOL_PREFIX: [u8; 5] = [0x55, 0xB5, 0x00, 0x00, 0x00];
